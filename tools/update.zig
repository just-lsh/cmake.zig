//! Updates the CMake, Ninja, Python and pkgconf URLs and hashes in
//! build.zig.zon (between the "begin tools" and "end tools" comments) and
//! src/versions.zig. Run as:
//!
//!   zig build update-tools -- cmake=4.4.5 ninja=1.13.2 python=3.13.18+20261026 pkgconf=3.0.10
//!
//! Each archive is fetched with a temporary global cache and package
//! directory, so nothing is left behind (a tarball in the global cache would
//! otherwise be unpacked into zig-pkg/ even for lazy dependencies).
const std = @import("std");
const Io = std.Io;
const Allocator = std.mem.Allocator;
const fatal = std.process.fatal;

const Versions = struct {
    cmake: []const u8 = "",
    ninja: []const u8 = "",
    python: []const u8 = "",
    pkgconf: []const u8 = "",
};

const Dep = struct { name: []const u8, url: []const u8 };

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 3) fatal("usage: update-tools <zig> <build.zig.zon> cmake=<v> ninja=<v> python=<v>+<build> pkgconf=<v>", .{});
    const zig = args[1];
    const zon_path = args[2];

    var v: Versions = .{};
    for (args[3..]) |arg| {
        const eq = std.mem.indexOfScalar(u8, arg, '=') orelse fatal("expected <tool>=<version>: {s}", .{arg});
        inline for (comptime std.meta.fieldNames(Versions)) |name| {
            if (std.mem.eql(u8, arg[0..eq], name)) {
                @field(v, name) = arg[eq + 1 ..];
                break;
            }
        } else fatal("unknown tool: {s}", .{arg[0..eq]});
    }
    inline for (comptime std.meta.fieldNames(Versions)) |name| {
        if (@field(v, name).len == 0) fatal("missing {s}=<version>", .{name});
    }
    const plus = std.mem.indexOfScalar(u8, v.python, '+') orelse fatal("python=<version>+<build date>, e.g. 3.13.18+20261026", .{});
    const py_version = v.python[0..plus];
    const py_build = v.python[plus + 1 ..];

    var deps: std.ArrayList(Dep) = .empty;
    const cmake_url = "https://github.com/Kitware/CMake/releases/download/v{0s}/cmake-{0s}-{1s}";
    for ([_][2][]const u8{
        .{ "cmake_linux_x86_64", "linux-x86_64.tar.gz" },
        .{ "cmake_linux_aarch64", "linux-aarch64.tar.gz" },
        .{ "cmake_macos", "macos-universal.tar.gz" },
        .{ "cmake_windows_x86_64", "windows-x86_64.zip" },
        .{ "cmake_windows_aarch64", "windows-arm64.zip" },
    }) |d| try deps.append(arena, .{ .name = d[0], .url = try std.fmt.allocPrint(arena, cmake_url, .{ v.cmake, d[1] }) });
    const ninja_url = "https://github.com/ninja-build/ninja/releases/download/v{s}/ninja-{s}";
    for ([_][2][]const u8{
        .{ "ninja_linux_x86_64", "linux.zip" },
        .{ "ninja_linux_aarch64", "linux-aarch64.zip" },
        .{ "ninja_macos", "mac.zip" },
        .{ "ninja_windows_x86_64", "win.zip" },
        .{ "ninja_windows_aarch64", "winarm64.zip" },
    }) |d| try deps.append(arena, .{ .name = d[0], .url = try std.fmt.allocPrint(arena, ninja_url, .{ v.ninja, d[1] }) });
    const python_url = "https://github.com/astral-sh/python-build-standalone/releases/download/{0s}/cpython-{1s}%2B{0s}-{2s}-install_only_stripped.tar.gz";
    for ([_][2][]const u8{
        .{ "python_linux_x86_64", "x86_64-unknown-linux-gnu" },
        .{ "python_linux_aarch64", "aarch64-unknown-linux-gnu" },
        .{ "python_macos_x86_64", "x86_64-apple-darwin" },
        .{ "python_macos_aarch64", "aarch64-apple-darwin" },
        .{ "python_windows_x86_64", "x86_64-pc-windows-msvc" },
        .{ "python_windows_aarch64", "aarch64-pc-windows-msvc" },
    }) |d| try deps.append(arena, .{ .name = d[0], .url = try std.fmt.allocPrint(arena, python_url, .{ py_build, py_version, d[1] }) });
    try deps.append(arena, .{
        .name = "pkgconf",
        .url = try std.fmt.allocPrint(arena, "https://github.com/pkgconf/pkgconf/archive/refs/tags/pkgconf-{s}.tar.gz", .{v.pkgconf}),
    });

    // A temporary global cache and package directory for zig fetch.
    const cwd = Io.Dir.cwd();
    const tmp = ".zig-cache/update-tools";
    cwd.deleteTree(io, tmp) catch {};
    try cwd.createDirPath(io, tmp);
    defer cwd.deleteTree(io, tmp) catch {};
    var env = try init.environ_map.clone(arena);
    try env.put("ZIG_GLOBAL_CACHE_DIR", tmp ++ "/global");

    var block: Io.Writer.Allocating = .init(arena);
    const w = &block.writer;
    try w.writeAll("        // begin tools (generated by tools/update.zig)\n");
    for (deps.items) |dep| {
        std.log.info("fetching {s}", .{dep.url});
        const result = try std.process.run(arena, io, .{
            .argv = &.{ zig, "fetch", "--pkg-dir", tmp ++ "/pkg", dep.url },
            .environ_map = &env,
        });
        if (!result.term.success()) fatal("zig fetch {s} failed:\n{s}", .{ dep.url, result.stderr });
        const hash = std.mem.trim(u8, result.stdout, " \r\n");
        try w.print(
            \\        .{s} = .{{
            \\            .url = "{s}",
            \\            .hash = "{s}",
            \\            .lazy = true,
            \\        }},
            \\
        , .{ dep.name, dep.url, hash });
    }
    try w.writeAll("        // end tools\n");

    const zon = try cwd.readFileAlloc(io, zon_path, arena, .limited(1 << 20));
    const begin_marker = "        // begin tools";
    const end_marker = "        // end tools\n";
    const begin = std.mem.indexOf(u8, zon, begin_marker) orelse fatal("no '{s}' in {s}", .{ begin_marker, zon_path });
    const end = (std.mem.indexOf(u8, zon, end_marker) orelse fatal("no '{s}' in {s}", .{ end_marker, zon_path })) + end_marker.len;
    const new_zon = try std.mem.concat(arena, u8, &.{ zon[0..begin], block.written(), zon[end..] });
    try cwd.writeFile(io, .{ .sub_path = zon_path, .data = new_zon });

    const versions_path = try std.fs.path.join(arena, &.{ std.fs.path.dirname(zon_path) orelse ".", "src", "versions.zig" });
    try cwd.writeFile(io, .{ .sub_path = versions_path, .data = try std.fmt.allocPrint(arena,
        \\//! The tool versions in build.zig.zon. Generated by tools/update.zig.
        \\pub const cmake = "{s}";
        \\pub const ninja = "{s}";
        \\pub const python = "{s}";
        \\pub const pkgconf = "{s}";
        \\
    , .{ v.cmake, v.ninja, v.python, v.pkgconf }) });
}
